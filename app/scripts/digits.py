# Bakes the large-number glyphs into app/digits.ts, so every phone draws the same pixels.
# Usage: python3 app/scripts/digits.py  (needs Pillow and Noto Sans Medium, OFL).
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

CHARS = '0123456789.,$+-~%'
HEIGHT, BASELINE, SIZE = 60, 50, 62  # digits come out about 44 px tall
font = ImageFont.truetype('/usr/share/fonts/noto/NotoSans-Medium.ttf', SIZE)

out = ['// Generated by scripts/digits.py from Noto Sans Medium (SIL Open Font License). Do not edit.',
       '// Each glyph: advance, ink box (x, y, w) and one hex digit per pixel, brightness 0-15.',
       'export type Glyph = [advance: number, x: number, y: number, w: number, hex: string]',
       'export const glyphs: Record<string, Glyph> = {']
for ch in CHARS:
    advance = round(font.getlength(ch))
    img = Image.new('L', (advance + 8, HEIGHT))
    ImageDraw.Draw(img).text((0, BASELINE), ch, font=font, fill=255, anchor='ls')
    box = img.getbbox()
    if not box:
        continue
    x0, y0, x1, y1 = box
    hexes = ''.join('%x' % round(v * 15 / 255) for v in img.crop(box).tobytes())
    out.append(f"  {ch!r}: [{advance}, {x0}, {y0}, {x1 - x0}, '{hexes}'],")
out.append('}')
Path(__file__).resolve().parent.parent.joinpath('digits.ts').write_text('\n'.join(out) + '\n')
