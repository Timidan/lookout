export function monogram(text: string): Icon {
  const normalized = text.normalize('NFKD').toUpperCase()
  const initials = (normalized.replace(/[^A-Z0-9]/g, '') ||
    normalized.codePointAt(0)?.toString(36).toUpperCase() || '?').slice(0, 2)
  const glyphs = Array.from(initials, char => badgeFont[char]!)
  const width = glyphs.length === 1 ? 16 : 9
  const left = glyphs.length === 1 ? 4 : 2
  const badge = new Uint8Array(72)
  for (let y = 0; y < SIDE; y++) {
    const row = Math.floor((y - 3) / 3)
    for (let x = 0; x < SIDE; x++) {
      if ((x < 2 || x >= 22) && (y < 2 || y >= 22)) continue
      const offset = x - left
      const glyph = glyphs[Math.floor(offset / (width + 2))]
      const col = Math.floor((offset % (width + 2)) * 4 / width)
      if (glyph?.[row]?.[col] !== '#') light(badge, x, y)
    }
  }
  return badge
}

