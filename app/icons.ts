// Store tiles can start at either parity. Overlapping 2 × 2 tiles may cover a single shape.
export function validStoreIcon(icon: Icon): boolean {
  if (icon.length !== SIDE * SIDE / 8) return false
  const covered = new Uint8Array(icon.length)
  for (let y = 0; y < SIDE - 1; y++) {
    for (let x = 0; x < SIDE - 1; x++) {
      if (isLit(icon, x, y) && isLit(icon, x + 1, y) &&
          isLit(icon, x, y + 1) && isLit(icon, x + 1, y + 1)) {
        light(covered, x, y)
        light(covered, x + 1, y)
        light(covered, x, y + 1)
        light(covered, x + 1, y + 1)
      }
    }
  }
  return icon.every((byte, i) => byte === covered[i])
}

