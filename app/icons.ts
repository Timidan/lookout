export function coinIcon(symbol: string): Icon {
  const base = symbol.split('/', 1)[0]!
  const name = base.slice(base.lastIndexOf(':') + 1).trim().toUpperCase()
  const drawing = Object.hasOwn(coins, name) ? coins[name as keyof typeof coins] : undefined
  return drawing ?? monogram(name)
}

export function actionLabel(name: ActionName): string {
  if (name === 'protected') return 'Stop set'
  if (name === 'unprotected') return 'No stop'
  return name.replace(/[A-Z]/g, c => ' ' + c.toLowerCase()).replace(/^./, c => c.toUpperCase())
}

export function actionIcon(name: ActionName): Icon {
  return actions[name]
}

// SDK input verified on simulator 0.9.5: row-major Gray4, left pixel in the high nibble.
// 24..288 px wide, 24 px high. The 24 px cells are adjacent, with no inserted padding.
export function iconRowBytes(icons: readonly Icon[], brightness = 15): Uint8Array {
  if (icons.length < 1 || icons.length > 12) throw new RangeError('Use 1 to 12 icons per row')
  if (!Number.isInteger(brightness) || brightness < 0 || brightness > 15) throw new RangeError('Brightness must be an integer from 0 to 15')
  const pitch = icons.length * SIDE / 2
  const bytes = new Uint8Array(pitch * SIDE)
  for (const [index, icon] of icons.entries()) {
    if (icon.length !== 72) throw new Error('Expected a packed 24 × 24 icon')
    for (let y = 0; y < SIDE; y++) {
      for (let x = 0; x < SIDE; x += 2) {
        const left = isLit(icon, x, y) ? brightness : 0
        const right = isLit(icon, x + 1, y) ? brightness : 0
        bytes[y * pitch + index * 12 + x / 2] = (left << 4) | right
      }
    }
  }
  return bytes
}
