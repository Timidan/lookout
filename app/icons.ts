// Each drawing below has 24 rows of 24 pixels. Keep the rows readable when editing.
// Runtime storage is 72 bytes per icon, MSB first, three bytes per scanline.
export type Icon = Uint8Array
const SIDE = 24

export function bitmap(source: string): Icon {
  const rows = source.replace(/^\n|\n$/g, '').split('\n')
  if (rows.length !== SIDE) throw new Error(`Expected 24 icon rows, received ${rows.length}`)
  const packed = new Uint8Array(72)
  for (const [y, row] of rows.entries()) {
    if (row.length !== SIDE) throw new Error(`Icon row ${y + 1} must have 24 columns`)
    if (/[^.#]/.test(row)) throw new Error(`Invalid pixel in icon row ${y + 1}; use . or #`)
    for (let x = 0; x < SIDE; x++) if (row[x] === '#') light(packed, x, y)
  }
  return packed
}

function light(icon: Icon, x: number, y: number) {
  const offset = y * 3 + (x >> 3)
  icon[offset] = icon[offset]! | (128 >> (x & 7))
}

export function isLit(icon: Icon, x: number, y: number): boolean {
  return (icon[y * 3 + (x >> 3)]! & (128 >> (x & 7))) !== 0
}
